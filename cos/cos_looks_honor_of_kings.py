def _complete_honor_of_kings_prompt(look: Dict[str, Any]) -> str:
    """Organize verified costume notes without inventing missing details."""
    raw_prompt = str(look.get("prompt") or "").strip()
    details = raw_prompt.split("：", 1)[-1].strip().rstrip("。")
    clauses = [
        part.strip(" ，,。；;\n\t")
        for clause in re.split(r"[；;。\n]+", details)
        for part in re.split(r"[，,]", clause)
        if part.strip(" ，,。；;\n\t")
    ]

    costume_details: List[str] = []
    exclusions: List[str] = []
    for clause in clauses:
        if _COS_HOK_STAGING_TERMS.search(clause):
            continue
        if _COS_HOK_EXCLUSION_TERMS.search(clause):
            exclusions.append(clause)
        else:
            costume_details.append(clause)

    title = str(look.get("title") or "").strip()
    section_labels = {
        "head": "假发与头部固定饰件",
        "upper": "上身衣装与层次",
        "waist": "腰线及上下装连接",
        "lower": "下装轮廓与层次",
        "feet": "袜履与鞋型",
        "material": "面料、纹样与固定饰件材质",
    }
    section_lines = []
    section_details = {section: [] for section in _COS_HOK_DETAIL_SECTIONS}
    unassigned_details = []
    for clause in costume_details:
        section = next(
            (
                name
                for name, pattern in _COS_HOK_DETAIL_SECTIONS.items()
                if pattern.search(clause)
            ),
            "",
        )
        if section:
            section_details[section].append(clause)
        else:
            unassigned_details.append(clause)
    if unassigned_details:
        section_lines.append("配色与整体辨识：" + "；".join(unassigned_details))
    for section in _COS_HOK_DETAIL_SECTIONS:
        matched = list(dict.fromkeys(section_details[section]))
        if matched:
            section_lines.append(f"{section_labels[section]}：" + "；".join(matched))
    lines = [
        "身份与参考图边界：以形象参考图中的人为唯一COS主体，保留本人的性别、年龄感、脸部身份和五官比例；视觉媒介遵循本次形象类型设置，自动模式沿用主身份参考图媒介；不用游戏原画人物的脸替换本人。",
        f"皮肤版本锁定：按《王者荣耀》「{title}」制作单一皮肤的可穿戴COS造型，不混搭同角色基础造型或其他皮肤；只依据下列已核验的颜色、发型、标志饰件和衣装剪影。",
        *section_lines,
        "可穿戴转译：按现实服装结构呈现已列明的衣物和固定饰件；金属、羽纹、花纹、晶体或能量意象只在已明确时转为衣料纹样或固定饰件，不生成额外肢体或技能特效。",
        "还原边界：只采用上文明确列出的造型信息；未明确或参考立绘中无法确认的部件不补造，也不以通用服饰替代已写明结构。",
    ]
    if exclusions:
        lines.append("该套装专属排除项：" + "；".join(exclusions))
    return "\n".join(lines)


